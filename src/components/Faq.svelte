<div id="faq">
  <h2>Spørsmål du kanskje har</h2>

  <div id="questions">
    <div>
      <h3>Hva er Normantle/Semantle?</h3>
      <p>
        Et enkelt ordspill der man skal gjette seg til et ord hver dag. Spillet
        vil fortelle deg hvor mye ordene du gjetter ligner på dagens ord i
        betydning. Se <a href="https://semantle.com/">Semantle</a> sine egne sider
        for mer informasjon.
      </p>
    </div>

    <div>
      <h3>Når resettes klokka?</h3>
      <p>Klokken 00:00 norsk tid</p>
    </div>

    <div>
      <h3>Når blir et ord godkjent som "riktig"?</h3>
      <p>
        Bare når du gjetter nøyaktig dagens ord. Synonymer og ord som ligner mye
        kan få høy likhetsgrad, men blir ikke godkjent.
      </p>
    </div>

    <div>
      <h3>Hva slags ord kan være dagens ord?</h3>
      <p>
        Dagens ord er alltid et substantiv. Du kan likevel gjette verb,
        adjektiver og adverb for å finne ut hva ordet handler om, men de kan
        aldri være riktig svar.
      </p>
    </div>

    <div>
      <h3>Går det an å skrive på nynorsk?</h3>
      <p>
        Nei. Spillet godtar bare bokmålsord som står i <a
          href="https://www.nb.no/sprakbanken/ressurskatalog/oai-nb-no-sbr-5/"
          >Norsk ordbank</a
        >. Nynorsk, feilstavinger og småord som "og" og "hvorfor" finnes derfor
        ikke i ordlisten.
      </p>
    </div>

    <div>
      <h3>Spillet husker ikke progresjonen min!</h3>
      <p>
        Litt intensjonelt. Det finnes mange måter å "jukse" på, men du ødelegger
        bare for deg selv. Siden spillet er litt dårlig i sitt nåværende stadie
        ønsker jeg å gjøre det mest mulig lettvindt å starte på nytt.
      </p>
    </div>

    <div>
      <h3>Spillet suger og har masse feil i seg!</h3>
      <p>
        Da anbefaler jeg deg å rapportere om feilen på <a
          href="https://github.com/LBlend/normantle">Github</a
        > eller enda bedre, fikse feilen selv der.
      </p>
    </div>
  </div>
</div>

